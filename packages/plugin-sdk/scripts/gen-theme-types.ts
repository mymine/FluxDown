// Generates src/types/theme.d.ts from website-v2/src/lib/gpui-theme/registry.json.
// `--check` compares with the committed file and exits 1 on drift.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const REGISTRY = new URL("../../../website-v2/src/lib/gpui-theme/registry.json", import.meta.url);
const OUT = new URL("../src/types/theme.d.ts", import.meta.url);

interface Token {
  path: string;
  group: string;
  kind: string;
}
const registry: { schemaVersion: number; tokens: Token[] } = JSON.parse(readFileSync(REGISTRY, "utf8"));

const paths = registry.tokens.map((t) => t.path);
if (new Set(paths).size !== paths.length) throw new Error("registry has duplicate token paths");

const lines = [
  "// AUTO-GENERATED by scripts/gen-theme-types.ts from website-v2/src/lib/gpui-theme/registry.json.",
  "// Do not edit by hand; run `bun run gen`.",
  `// Theme registry schema version ${registry.schemaVersion}.`,
  "",
  "/** Every theme token path FluxDown resolves (the keys of `fluxdown.theme().tokens`). */",
  "export type ThemeTokenPath =",
  ...paths.map((p, i) => `  | ${JSON.stringify(p)}${i === paths.length - 1 ? ";" : ""}`),
  "",
  "/** A resolved token: `#rrggbbaa` for colors, a number for sizes / radii / weights, a string for fonts. */",
  "export type ThemeTokenValue = string | number;",
  "",
  "export interface ThemeSnapshot {",
  "  /** Bumps on every theme change. */",
  "  revision: number;",
  "  tokens: Record<ThemeTokenPath, ThemeTokenValue>;",
  "}",
  "",
];
const content = lines.join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
  if (current !== content) {
    console.error("src/types/theme.d.ts is out of date; run `bun run gen`.");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, content);
}
