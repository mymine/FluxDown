interface BaseProps {
  size?: number;
  class?: string;
  title?: string;
}

type IconProps = BaseProps &
  (
    | { name: UiIconName; fileName?: undefined; resourceType?: undefined; kind?: undefined }
    | { name?: undefined; fileName: string; resourceType?: undefined; kind?: undefined }
    | { name?: undefined; fileName?: undefined; resourceType: ResourceType; kind?: undefined }
    | { name?: undefined; fileName?: undefined; resourceType?: undefined; kind: FileIconKind }
  );

export function Icon(props: IconProps): JSX.Element {
  const size = props.size ?? 16;
  let inner: string;
  let cls = props.class ?? "";
  if (props.name) {
    inner = UI_PATHS[props.name];
  } else {
    const kind: FileIconKind =
      props.kind ??
      (props.resourceType ? resourceIconKind(props.resourceType) : fileIconKind(props.fileName ?? ""));
    inner = FILE_PATHS[kind];
    cls = `${cls} fd-icon-${kind}`.trim();
  }
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      stroke-width="1.8"
      stroke-linecap="round"
      stroke-linejoin="round"
      class={`fd-icon ${cls}`.trim()}
      aria-hidden="true"
      dangerouslySetInnerHTML={{ __html: inner }}
    />
  );
}
