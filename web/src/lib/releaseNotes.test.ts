import { describe, expect, test } from 'bun:test'
import { localizedReleaseBody, releaseDate, releaseNoteBlocks, stripVersionHeading } from './releaseNotes'

// 与 GPUI `crates/settings/src/sections/about.rs` 的测试为同一组用例。
describe('release notes', () => {
  test('按界面语言切段', () => {
    const body = '前言\n<!-- fluxdown:lang:zh -->\n## 问题修复\n- 修复下载\n<!-- fluxdown:lang:en -->\n## Bug Fixes\n- Fix downloads\n'
    for (const locale of ['zh', 'zh_CN', 'zh-Hans-CN', 'zh-Hant-TW', 'ZH_hk', 'zh-tw']) {
      expect(localizedReleaseBody(body, locale)).toBe('## 问题修复\n- 修复下载')
    }
    for (const locale of ['en', 'en-US', 'fr_FR', 'ja', '']) {
      expect(localizedReleaseBody(body, locale)).toBe('## Bug Fixes\n- Fix downloads')
    }
  })

  test('标记顺序与空白', () => {
    const body = '<!--fluxdown:lang:en-->\r\nEnglish\r\n<!--\tfluxdown:lang:zh\n-->\r\n中文\r\n'
    expect(localizedReleaseBody(body, 'en')).toBe('English')
    expect(localizedReleaseBody(body, 'zh')).toBe('中文')
  })

  test('历史说明原样返回，缺语言用已有语言', () => {
    const legacy = '## 旧版本\nUntranslated notes\n<!-- unrelated -->'
    expect(localizedReleaseBody(legacy, 'zh')).toBe(legacy)
    expect(localizedReleaseBody(legacy, 'en')).toBe(legacy)
    expect(localizedReleaseBody('<!-- fluxdown:lang:zh -->\n中文', 'en')).toBe('中文')
    expect(localizedReleaseBody('<!-- fluxdown:lang:en -->\nEnglish', 'zh')).toBe('English')
  })

  test('去掉与标题重复的版本标题', () => {
    expect(stripVersionHeading('## 0.5.7 - 2026-10-15\n\n### 🚀 新功能\n- 批量导入', '0.5.7')).toBe('### 🚀 新功能\n- 批量导入')
    for (const heading of ['## [0.5.6] - 2026-10-12', '## v0.5.6 - 2026-10-12', '# 0.5.6']) {
      const body = `${heading}\r\n\r\n- fix\r\n`
      expect(stripVersionHeading(body, '0.5.6')).toBe('- fix\r\n')
      expect(stripVersionHeading(body, 'v0.5.6')).toBe('- fix\r\n')
    }
    expect(stripVersionHeading('\n  ## 0.5.7\n', '0.5.7')).toBe('')
  })

  test('保留其它版本与章节标题', () => {
    const cases: [string, string][] = [
      ['## 0.5.10 - 2026-11-01\n- a', '0.5.1'],
      ['## 0.5.7-rc.1 - 2026-10-14\n- a', '0.5.7'],
      ['## 问题修复\n- a', '0.5.7'],
      ['##0.5.7\n- a', '0.5.7'],
      ['####### 0.5.7\n- a', '0.5.7'],
      ['- 0.5.7 修复\n## 0.5.7', '0.5.7'],
      ['## 0.5.7\n- a', ''],
    ]
    for (const [body, version] of cases) {
      expect(stripVersionHeading(body, version)).toBe(body)
    }
  })

  test('发布日期取 ISO 时间的日期部分', () => {
    expect(releaseDate('2026-10-15T06:14:16Z')).toBe('2026-10-15')
    expect(releaseDate(' 2026-10-15 ')).toBe('2026-10-15')
    expect(releaseDate('2026-10-15 06:14:16')).toBe('2026-10-15')
    for (const invalid of ['', '2026-10', '2026/10/15T00:00:00Z', '2026-10-150', '十月十五日之后']) {
      expect(releaseDate(invalid)).toBeNull()
    }
  })

  test('正文拆成标题、列表与段落', () => {
    const body = [
      '### 🚀 新功能',
      '- 批量导入',
      '  - 分块提交',
      '- 支持 aria2c 命令',
      '  续行并入上一项',
      '',
      '---',
      '说明第一行',
      '说明第二行',
      '',
      '**粗体开头的段落**',
      '#',
    ].join('\r\n')
    expect(releaseNoteBlocks(body)).toEqual([
      { kind: 'heading', text: '🚀 新功能' },
      {
        kind: 'list',
        items: [
          { text: '批量导入', depth: 0 },
          { text: '分块提交', depth: 1 },
          { text: '支持 aria2c 命令 续行并入上一项', depth: 0 },
        ],
      },
      { kind: 'paragraph', lines: ['说明第一行', '说明第二行'] },
      { kind: 'paragraph', lines: ['**粗体开头的段落**'] },
    ])
    expect(releaseNoteBlocks('')).toEqual([])
  })

  test('HTML 注释不显示', () => {
    const legacy = '### 🐛 Bug Fixes\n\n- *(nmh)* 立即退出\n\n<!-- generated by git-cliff -->\n'
    expect(releaseNoteBlocks(legacy)).toEqual([
      { kind: 'heading', text: '🐛 Bug Fixes' },
      { kind: 'list', items: [{ text: '*(nmh)* 立即退出', depth: 0 }] },
    ])
    expect(releaseNoteBlocks('前<!-- 跨\n行 -->后')).toEqual([{ kind: 'paragraph', lines: ['前后'] }])
  })
})
