// 更新说明（移植 GPUI `crates/settings/src/sections/about.rs` 的同名规则）：按界面语言切段、
// 去掉正文开头与标题重复的版本标题、取发布日期；另把正文拆成标题 / 列表 / 段落块供页面渲染
// （Web 不引入 Markdown 渲染器，行内标记按原文显示）。

/**
 * 按界面语言取更新说明的语言区块：正文以 `<!-- fluxdown:lang:zh -->` / `<!-- fluxdown:lang:en -->`
 * 分段；中文界面取中文，其余取英文，缺目标语言时用已有语言，无标记的历史说明原样返回。
 */
export function localizedReleaseBody(body: string, locale: string): string {
  const language = locale.trim().split(/[-_.@]/)[0] ?? ''
  const chinese = language.toLowerCase() === 'zh'
  const sections: [string | null, string | null] = [null, null]
  let previous: [number, number] | null = null
  let cursor = 0
  for (;;) {
    const start = body.indexOf('<!--', cursor)
    if (start < 0) break
    const contentStart = start + '<!--'.length
    const contentEnd = body.indexOf('-->', contentStart)
    if (contentEnd < 0) break
    cursor = contentEnd + '-->'.length
    const marker = body.slice(contentStart, contentEnd).trim()
    const index = marker === 'fluxdown:lang:zh' ? 0 : marker === 'fluxdown:lang:en' ? 1 : -1
    if (index < 0) continue
    if (previous) sections[previous[0]] = body.slice(previous[1], start).trim()
    previous = [index, cursor]
  }
  if (previous) sections[previous[0]] = body.slice(previous[1]).trim()
  return sections[chinese ? 0 : 1] ?? sections[0] ?? sections[1] ?? body
}

/** ATX 标题（1–6 个 `#` 后接空白或行尾）的标题文字；不是标题时为 null。 */
function atxHeadingText(line: string): string | null {
  const text = line.replace(/^#+/, '')
  const level = line.length - text.length
  if (level < 1 || level > 6) return null
  if (text !== '' && !/^[ \t]/.test(text)) return null
  return text.trim()
}

/**
 * 去掉正文开头与标题重复的版本标题（`## 0.5.7 - 2026-10-15`、`## [0.5.6] - …`、`## v0.4.8 - …`）。
 * 只认首个非空行、且标题文字以该版本号开头（其后不是版本号字符）；其它开头原样保留。
 */
export function stripVersionHeading(body: string, version: string): string {
  const text = body.trimStart()
  const wanted = version.trim().replace(/^[vV]+/, '')
  const newline = text.indexOf('\n')
  const first = newline < 0 ? text : text.slice(0, newline)
  const rest = newline < 0 ? '' : text.slice(newline + 1)
  const title = atxHeadingText(first.trimEnd())
  if (title === null || wanted === '') return text
  const label = title.replace(/^\[+/, '').replace(/^[vV]+/, '')
  if (!label.startsWith(wanted)) return text
  const next = label.charAt(wanted.length)
  if (next !== '' && /[\p{L}\p{N}._+-]/u.test(next)) return text
  return rest.trimStart()
}

/** 发布时间（ISO 8601）的日期部分 `YYYY-MM-DD`；不是该格式时为 null，标题只显示版本。 */
export function releaseDate(publishedAt: string): string | null {
  const value = publishedAt.trim()
  const date = value.slice(0, 10)
  const rest = value.slice(10)
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) return null
  return rest === '' || /^[Tt ]/.test(rest) ? date : null
}

export interface ReleaseNoteItem {
  text: string
  /** 嵌套层级（0 起，按缩进每 2 格一级，最多 3）。 */
  depth: number
}

export type ReleaseNoteBlock =
  | { kind: 'heading'; text: string }
  | { kind: 'list'; items: ReleaseNoteItem[] }
  | { kind: 'paragraph'; lines: string[] }

const LIST_ITEM = /^(\s*)[-*+]\s+(.*)$/
const THEMATIC_BREAK = /^\s*([-*_])(?:\s*\1){2,}\s*$/
const MAX_LIST_DEPTH = 3

/**
 * 把更新说明拆成块：`#` 标题、`-` / `*` / `+` 列表项（缩进表示嵌套，紧随其后的非空行并入上一项）、
 * 其余为段落（保留原有换行）；空行与分隔线（`---`）分隔块。HTML 注释（如 git-cliff 生成的
 * `<!-- generated by git-cliff -->`）不显示，与 GPUI / Android 的 Markdown 渲染一致。
 */
export function releaseNoteBlocks(markdown: string): ReleaseNoteBlock[] {
  const blocks: ReleaseNoteBlock[] = []
  let paragraph: string[] = []
  let items: ReleaseNoteItem[] = []
  const flushParagraph = () => {
    if (paragraph.length > 0) blocks.push({ kind: 'paragraph', lines: paragraph })
    paragraph = []
  }
  const flushList = () => {
    if (items.length > 0) blocks.push({ kind: 'list', items })
    items = []
  }
  for (const raw of markdown.replace(/<!--[\s\S]*?-->/g, '').split('\n')) {
    const line = raw.trimEnd()
    if (line.trim() === '' || THEMATIC_BREAK.test(line)) {
      flushParagraph()
      flushList()
      continue
    }
    const heading = atxHeadingText(line.trimStart())
    if (heading !== null) {
      flushParagraph()
      flushList()
      if (heading !== '') blocks.push({ kind: 'heading', text: heading })
      continue
    }
    const item = LIST_ITEM.exec(line)
    if (item) {
      flushParagraph()
      const indent = item[1]?.replace(/\t/g, '  ').length ?? 0
      items.push({ text: (item[2] ?? '').trim(), depth: Math.min(Math.floor(indent / 2), MAX_LIST_DEPTH) })
      continue
    }
    const last = items[items.length - 1]
    if (last) {
      last.text = `${last.text} ${line.trim()}`.trim()
      continue
    }
    paragraph.push(line.trim())
  }
  flushParagraph()
  flushList()
  return blocks
}
